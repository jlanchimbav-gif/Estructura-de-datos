# Tipos de Arboles
# 1. Árbol Binario : Un árbol binario es un árbol en el que cada nodo tiene cero o dos hijos.
# 2. Árbol Binario de Búsqueda : Un árbol binario de búsqueda es un árbol binario en el que cada nodo 
# tiene un valor y los valores de los nodos hijo izquierdo son menores que el valor del nodo padre y 
# los valores de los nodos hijo derecho son mayores que el valor del nodo padre.
# 3. Árbol AVL : Un árbol AVL es un árbol binario de búsqueda en el que la diferencia de altura entre 
# los hijos izquierdo y derecho de cada nodo es como máximo 1.
# 4. Árbol Rojo y Negro : Un árbol rojo y negro es un árbol binario de búsqueda en el que cada nodo 
# tiene un color y los colores de los nodos hijo izquierdo son rojos y los colores de los nodos hijo derecho son negros.
# 5. Árbol B : Un árbol B es un árbol binario de búsqueda en el que cada nodo tiene un valor y los valores
# de los nodos hijo izquierdo son menores que el valor del nodo padre y los valores de los nodos 
# hijo derecho son mayores que el valor del nodo padre.
