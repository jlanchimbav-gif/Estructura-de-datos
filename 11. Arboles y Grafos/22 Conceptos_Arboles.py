# Definición : Un árbol es una estructura de datos no lineal que se compone de nodos y aristas.
# Características :
# 1. Un árbol debe tener un nodo raíz.
# 2. Cada nodo puede tener cero o más nodos hijos.
# 3. Cada nodo puede tener cero o un nodo padre.
# 4. Cada nodo puede tener cero o más nodos hermanos.

# Recorridos 
# 1 Altura : La altura de un árbol es la longitud del camino más largo desde la raíz hasta una hoja.
# 2 Profundidad : La profundidad de un nodo es la longitud del camino desde la raíz hasta el nodo.
# 3 Ancho : El ancho de un árbol es el número de nodos en el nivel más ancho.
# 4 Tamaño : El tamaño de un árbol es el número de nodos que contiene.
# 5 Grado : El grado de un árbol es el número de hijos que tiene el nodo con más hijos.
# 6 Orden : El orden de un árbol es el número de hijos que tiene el nodo con más hijos.
# 7 Fondo : El fondo de un árbol es el número de nodos en el nivel más profundo.
# 8 Diámetro : El diámetro de un árbol es la longitud del camino más largo desde una hoja hasta otra.
# 9 Centro : El centro de un árbol es el nodo que está a la misma distancia de todas las hojas.
# 10 Centroide : El centroide de un árbol es el nodo que está a la misma distancia de todas las hojas.

# Definiciones de Arboles
