# Definición : Un grafo es una estructura de datos no lineal que se compone de nodos y aristas.
# Características :
# 1. Un grafo debe tener un nodo raíz.
# 2. Cada nodo puede tener cero o más nodos hijos.
# 3. Cada nodo puede tener cero o un nodo padre.
# 4. Cada nodo puede tener cero o más nodos hermanos.

# Definiciones de Grafos
# 1. Grafo : Un grafo es una estructura de datos no lineal que se compone de nodos y aristas.
# 2. Nodo : Un nodo es un elemento que contiene un valor y tiene cero o más nodos hijos.
# 3. Nodo raíz : El nodo raíz es el nodo que está en la cima del grafo.
# 4. Nodo hoja : Un nodo hoja es un nodo que no tiene hijos.
# 5. Nodo interno : Un nodo interno es un nodo que tiene hijos.
# 6. Arista : Una arista es un enlace entre dos nodos.
# 7. Vertice : Un vertice es un nodo que tiene cero o más aristas.

# Recorridos
# 1. Recorrido en profundidad : Recorre el grafo desde un nodo raíz hasta el nodo hoja.
# 2. Recorrido en anchura : Recorre el grafo desde un nodo raíz hasta el nodo hoja.

# Tipos de Grafos
# 1. Grafo Dirigido : Un grafo dirigido es un grafo en el que las aristas tienen un sentido.
# 2. Grafo No Dirigido : Un grafo no dirigido es un grafo en el que las aristas no tienen un sentido.
# 3. Grafo Ponderado : Un grafo ponderado es un grafo en el que las aristas tienen un peso.
# 4. Grafo No Ponderado : Un grafo no ponderado es un grafo en el que las aristas no tienen un peso.
# 5. Grafo Conexo : Un grafo conexo es un grafo en el que todos los nodos están conectados.
# 6. Grafo No Conexo : Un grafo no conexo es un grafo en el que no todos los nodos están conectados.
# 7. Grafo Cíclico : Un grafo cíclico es un grafo en el que hay un ciclo.
# 8. Grafo No Cíclico : Un grafo no cíclico es un grafo en el que no hay un ciclo.

